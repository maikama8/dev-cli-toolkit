/** Names and descriptions, in catalog order. */
export function listTemplates(): { name: string; description: string }[] {
  return Object.entries(templates).map(([name, template]) => ({
    name,
    description: template.description,
  }));
}

/** Turn a directory name into an npm-safe slug. An empty result becomes `app`. */
export function projectName(dirName: string): string {
  const cleaned = dirName
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return cleaned || "app";
}

/** Substitute the project name into every template file. */
export function renderFiles(files: Record<string, string>, name: string): Record<string, string> {
  const rendered: Record<string, string> = {};
  for (const [path, content] of Object.entries(files)) {
    rendered[path] = content.replaceAll(PLACEHOLDER, name);
  }
  return rendered;
}

/**
 * Write a template into `dest`.
 * Existing files are left in place unless `force` is set.
 */
export async function scaffoldProject(options: {
  template: string;
  dest: string;
  force: boolean;
  cwd: string;
}): Promise<ScaffoldResult> {
  const catalog = templates[options.template];
  if (!catalog) {
    throw new ZtError(
      `unknown template "${options.template}". Choose ${Object.keys(templates).join(", ")}`,
      "TEMPLATE",
    );
  }
  const directory = resolve(options.cwd, options.dest);
  await mkdir(directory, { recursive: true });
  const name = projectName(basename(directory));
  const rendered = renderFiles(catalog.files, name);
  const conflicts = Object.keys(rendered).filter((file) => existsSync(join(directory, file)));
  if (conflicts.length > 0 && !options.force) {
    throw new ZtError(
      `refusing to overwrite ${conflicts.join(", ")} (pass --force)`,
      "EXISTS",
      1,
      false,
      { conflicts },
    );
  }
  for (const [file, content] of Object.entries(rendered)) {
    const target = join(directory, file);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content, "utf8");
  }
  return {
    template: options.template,
    directory: options.dest,
    name,
    files: Object.keys(rendered),
  };
}

/** Format `zt init --list` for a terminal. */
export function formatTemplateList(items: { name: string; description: string }[]): string {
  const width = Math.max(...items.map((item) => item.name.length));
  return items.map((item) => `${item.name.padEnd(width)}  ${item.description}`).join("\n");
}

/** Format a finished scaffold for a terminal. */
export function formatScaffold(result: ScaffoldResult, paint: Paint): string {
  const lines = [`${paint.green("created")} ${result.name} from ${result.template}`];
  for (const file of result.files) lines.push(`  ${file}`);
  return lines.join("\n");
}
